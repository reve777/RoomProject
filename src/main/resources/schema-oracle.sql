-- Roles Table
CREATE TABLE ROLES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(50) NOT NULL UNIQUE
);

-- Users Table
CREATE TABLE USERS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR2(100) NOT NULL UNIQUE,
    EMAIL VARCHAR2(150) NOT NULL UNIQUE,
    PASSWORD VARCHAR2(255) NOT NULL,
    FULL_NAME VARCHAR2(150),
    PHONE VARCHAR2(50),
    TWO_FACTOR_ENABLED NUMBER(1) DEFAULT 0 NOT NULL,
    TWO_FACTOR_SECRET VARCHAR2(100),
    OAUTH_PROVIDER VARCHAR2(50),
    OAUTH_ID VARCHAR2(255),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- User-Roles Join Table
CREATE TABLE USER_ROLES (
    USER_ID NUMBER NOT NULL,
    ROLE_ID NUMBER NOT NULL,
    PRIMARY KEY (USER_ID, ROLE_ID),
    CONSTRAINT FK_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_ROLE FOREIGN KEY (ROLE_ID) REFERENCES ROLES (ID) ON DELETE CASCADE
);

-- Rooms Table (Hotel / Room inventory)
CREATE TABLE ROOMS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(150) NOT NULL,
    ROOM_TYPE VARCHAR2(50) NOT NULL,
    PRICE_PER_NIGHT NUMBER(10, 2) NOT NULL,
    CAPACITY NUMBER(3) NOT NULL,
    DESCRIPTION CLOB,
    STATUS VARCHAR2(30) DEFAULT 'AVAILABLE' NOT NULL,
    AMENITIES VARCHAR2(500),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Room Images Table (Multiple Images per Room)
CREATE TABLE ROOM_IMAGES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ROOM_ID NUMBER NOT NULL,
    IMAGE_URL VARCHAR2(500) NOT NULL,
    FILE_NAME VARCHAR2(255) NOT NULL,
    IS_PRIMARY NUMBER(1) DEFAULT 0 NOT NULL,
    DISPLAY_ORDER NUMBER(3) DEFAULT 0,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_ROOM_IMAGE FOREIGN KEY (ROOM_ID) REFERENCES ROOMS (ID) ON DELETE CASCADE
);

-- Bookings Table
CREATE TABLE BOOKINGS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BOOKING_NUMBER VARCHAR2(50) NOT NULL UNIQUE,
    USER_ID NUMBER NOT NULL,
    ROOM_ID NUMBER NOT NULL,
    CHECK_IN_DATE DATE NOT NULL,
    CHECK_OUT_DATE DATE NOT NULL,
    TOTAL_PRICE NUMBER(10, 2) NOT NULL,
    STATUS VARCHAR2(30) DEFAULT 'CONFIRMED' NOT NULL,
    SPECIAL_REQUESTS VARCHAR2(1000),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_BOOKING_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_BOOKING_ROOM FOREIGN KEY (ROOM_ID) REFERENCES ROOMS (ID) ON DELETE CASCADE
);

